import json
import re
from dataclasses import dataclass
from typing import Dict, Any, Optional


@dataclass
class Action:
    """
    Structured action generated by the model output parser.
    
    Types:
    - 'tool_call': Model requested execution of a specific tool.
    - 'final': Model provided the task's final answer.
    - 'parse_error': Model output could not be parsed into a valid action structure.
    """
    action_type: str  # "tool_call", "final", "parse_error"
    tool_name: Optional[str] = None
    arguments: Optional[Dict[str, Any]] = None
    content: Optional[str] = None
    error_message: Optional[str] = None
    raw_output: str = ""

    def is_tool_call(self) -> bool:
        return self.action_type == "tool_call"

    def is_final_answer(self) -> bool:
        return self.action_type == "final"

    def is_parse_error(self) -> bool:
        return self.action_type == "parse_error"


class ModelOutputParser:
    """
    Pure syntax parser for model outputs.
    
    CRITICAL CONSTRAINT:
    The parser only extracts and validates syntax.
    It does NOT invent missing decisions, guess tool names, or fix semantic mistakes.
    """

    def parse(self, output_text: str) -> Action:
        raw_text = output_text.strip() if output_text else ""
        if not raw_text:
            return Action(
                action_type="parse_error",
                error_message="Model returned empty output.",
                raw_output=output_text,
            )

        # 1. Check for XML tag <tool_call>...</tool_call>
        tool_call_match = re.search(r"<tool_call>(.*?)</tool_call>", raw_text, re.DOTALL)
        if tool_call_match:
            json_str = tool_call_match.group(1).strip()
            return self._parse_json_tool_call(json_str, raw_text)

        # 2. Check for markdown json code block ```json ... ```
        code_block_match = re.search(r"```(?:json)?\s*(\{.*?\})\s*```", raw_text, re.DOTALL)
        if code_block_match:
            json_str = code_block_match.group(1).strip()
            action = self._try_parse_json(json_str, raw_text)
            if action:
                return action

        # 3. Check for raw JSON object in output
        json_obj_match = re.search(r"(\{.*\})", raw_text, re.DOTALL)
        if json_obj_match:
            json_str = json_obj_match.group(1).strip()
            action = self._try_parse_json(json_str, raw_text)
            if action:
                return action

        # 4. If no JSON structure is detected, treat as plain text Final Answer
        return Action(
            action_type="final",
            content=raw_text,
            raw_output=raw_text,
        )

    def _parse_json_tool_call(self, json_str: str, raw_text: str) -> Action:
        try:
            data = json.loads(json_str)
        except json.JSONDecodeError as err:
            return Action(
                action_type="parse_error",
                error_message=f"Malformed JSON inside <tool_call>: {str(err)}",
                raw_output=raw_text,
            )

        if not isinstance(data, dict):
            return Action(
                action_type="parse_error",
                error_message=f"<tool_call> payload must be a JSON object, got {type(data).__name__}.",
                raw_output=raw_text,
            )

        tool_name = data.get("name")
        arguments = data.get("arguments")

        if not tool_name or not isinstance(tool_name, str):
            return Action(
                action_type="parse_error",
                error_message="Tool call structure missing required string 'name' field.",
                raw_output=raw_text,
            )

        if arguments is None or not isinstance(arguments, dict):
            return Action(
                action_type="parse_error",
                error_message="Tool call structure missing required dictionary 'arguments' field.",
                raw_output=raw_text,
            )

        return Action(
            action_type="tool_call",
            tool_name=tool_name,
            arguments=arguments,
            raw_output=raw_text,
        )

    def _try_parse_json(self, json_str: str, raw_text: str) -> Optional[Action]:
        try:
            data = json.loads(json_str)
        except json.JSONDecodeError:
            return None

        if not isinstance(data, dict):
            return None

        action_type = data.get("type")

        # Explicit tool_call schema
        if action_type == "tool_call":
            tool_name = data.get("name")
            arguments = data.get("arguments")
            if not tool_name or not isinstance(tool_name, str):
                return Action(
                    action_type="parse_error",
                    error_message="tool_call action missing valid 'name' string field.",
                    raw_output=raw_text,
                )
            if arguments is None or not isinstance(arguments, dict):
                return Action(
                    action_type="parse_error",
                    error_message="tool_call action missing valid 'arguments' dictionary field.",
                    raw_output=raw_text,
                )
            return Action(
                action_type="tool_call",
                tool_name=tool_name,
                arguments=arguments,
                raw_output=raw_text,
            )

        # Explicit final answer schema
        if action_type == "final":
            content = data.get("content")
            if content is None:
                return Action(
                    action_type="parse_error",
                    error_message="final answer action missing required 'content' field.",
                    raw_output=raw_text,
                )
            return Action(
                action_type="final",
                content=str(content),
                raw_output=raw_text,
            )

        # Implicit tool call without explicit "type": "tool_call"
        if "name" in data and "arguments" in data:
            tool_name = data["name"]
            arguments = data["arguments"]
            if isinstance(tool_name, str) and isinstance(arguments, dict):
                return Action(
                    action_type="tool_call",
                    tool_name=tool_name,
                    arguments=arguments,
                    raw_output=raw_text,
                )

        return None
